-- v1.0.0 lead capture: public submissions are accepted only through the Edge Function.

CREATE TABLE lead (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email             text,
  instagram_handle  text,
  consented_at      timestamptz NOT NULL,
  source            text NOT NULL DEFAULT 'landing',
  medium            text,
  campaign          text,
  content           text,
  referrer          text,
  landing_path      text,
  status            text NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'CONTACTED', 'CONVERTED', 'UNSUBSCRIBED')),
  created_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT lead_contact_required CHECK (email IS NOT NULL OR instagram_handle IS NOT NULL),
  CONSTRAINT lead_email_length CHECK (email IS NULL OR char_length(email) BETWEEN 3 AND 254),
  CONSTRAINT lead_instagram_length CHECK (instagram_handle IS NULL OR char_length(instagram_handle) BETWEEN 1 AND 30)
);

CREATE UNIQUE INDEX lead_email_unique
  ON lead (lower(email)) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX lead_instagram_unique
  ON lead (lower(instagram_handle)) WHERE instagram_handle IS NOT NULL;
CREATE INDEX lead_created_at_idx ON lead (created_at DESC);

ALTER TABLE lead ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON lead FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON lead TO service_role;
GRANT USAGE, SELECT ON SEQUENCE lead_id_seq TO service_role;

COMMENT ON TABLE lead IS 'Launch leads. Writes are restricted to lead-capture Edge Function using service_role.';

